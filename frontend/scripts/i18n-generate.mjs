#!/usr/bin/env node
import { readdir, readFile, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "smol-toml";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const sourceDir = path.join(root, "assets/i18n");
const outDir = path.join(root, "src/i18n/messages");
const LOCALES = ["en", "zh-CN"];

async function main() {
  const files = (await readdir(sourceDir))
    .filter((name) => name.endsWith(".toml"))
    .sort();

  /** @type {Record<string, Record<string, Record<string, string>>>} */
  const catalogs = Object.fromEntries(LOCALES.map((locale) => [locale, {}]));
  /** @type {Record<string, string[]>} */
  const namespaceKeys = {};

  for (const file of files) {
    const namespace = path.basename(file, ".toml");
    const raw = await readFile(path.join(sourceDir, file), "utf8");
    const tables = parse(raw);
    namespaceKeys[namespace] = [];

    for (const locale of LOCALES) {
      catalogs[locale][namespace] = catalogs[locale][namespace] ?? {};
    }

    for (const [key, value] of Object.entries(tables)) {
      if (!value || typeof value !== "object" || Array.isArray(value)) {
        throw new Error(`${file}: expected table [${key}]`);
      }
      namespaceKeys[namespace].push(key);
      for (const locale of LOCALES) {
        const text = value[locale];
        if (typeof text !== "string") {
          throw new Error(`${file}: [${key}] missing ${locale}`);
        }
        catalogs[locale][namespace][key] = text;
      }
    }
    namespaceKeys[namespace].sort();
  }

  await mkdir(outDir, { recursive: true });
  for (const locale of LOCALES) {
    const target = path.join(outDir, `${locale}.json`);
    await writeFile(target, `${JSON.stringify(catalogs[locale], null, 2)}\n`, "utf8");
  }

  const dts = buildDts(namespaceKeys);
  await writeFile(path.join(root, "src/i18n/message-catalog.d.ts"), dts, "utf8");
  console.log(
    `i18n-generate: ${files.length} namespaces → ${LOCALES.join(", ")} (${Object.values(namespaceKeys).flat().length} keys)`,
  );
}

/** @param {Record<string, string[]>} namespaceKeys */
function buildDts(namespaceKeys) {
  const namespaces = Object.keys(namespaceKeys).sort();
  const nsUnion = namespaces.map((ns) => JSON.stringify(ns)).join(" | ");
  const blocks = namespaces.map((ns) => {
    const keys = namespaceKeys[ns]
      .map((key) => `    ${JSON.stringify(key)}: string;`)
      .join("\n");
    return `  ${JSON.stringify(ns)}: {\n${keys}\n  };`;
  });

  return `/* eslint-disable */
/* Generated by scripts/i18n-generate.mjs — do not edit by hand. */

export type AppLocale = "en" | "zh-CN";
export type MessageNamespace = ${nsUnion};

export type MessageCatalog = {
${blocks.join("\n")}
};

export type MessageKey<N extends MessageNamespace = MessageNamespace> =
  N extends MessageNamespace ? \`\${N}.\${Extract<keyof MessageCatalog[N], string>}\` : never;

declare const messages: Record<AppLocale, MessageCatalog>;
export default messages;
`;
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
